"""Writes trace_data.h for the serial emulator from the mock tests' recorded traces.

    python3 hardware/serial-emulator/make_trace.py

The emulator replays the same replies FakeOximeter does (tests/hwsim.py): the PO-400's Auto-mode
exchange (tests/fixtures/cli-exchange.trace.json) and its Manual-mode download
(tests/fixtures/manual-download.trace.json). Each entry is a command key (opcode plus the
argument bytes that identify it, as hwsim.command_key) and the reports the device sent back,
stored without their zero padding. Commands that got no reply are left out: the emulator stays
silent for anything not in the table, as the strict mock does. The 0x81 model reply is not
stored; the sketch builds it from the selected model string.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tests"))
from hwsim import Trace  # noqa: E402

FIXTURES = os.path.join(ROOT, "tests", "fixtures")
SOURCES = (("cli-exchange.trace.json", "AUTO"), ("manual-download.trace.json", "MANUAL"))
OUT = os.path.join(HERE, "trace_data.h")


def entries():
    """(flag, key bytes, [trimmed reports]) per distinct command key that got a reply."""
    seen = {}
    for name, storage in SOURCES:
        for _out, key, ins in Trace.from_json(os.path.join(FIXTURES, name)).groups:
            if key is None or key[0] in ("unlock", "destructive") or key == (0x81,) or not ins:
                continue
            flag = storage if (storage == "MANUAL" or key[0] in (0x9C, 0x9D)) else "COMMON"
            reports = [bytes(r).rstrip(b"\x00") or b"\x00" for r in ins]
            if key in seen:
                if seen[key][2] != reports:
                    raise SystemExit(f"{name}: {key} was recorded with two different replies")
                continue
            seen[key] = (flag, bytes(key), reports)
    return list(seen.values())


def render() -> str:
    lines = [
        "// Generated by make_trace.py from tests/fixtures/*.trace.json. Do not edit by hand.",
        "#pragma once",
        "",
        "// Entry: flags, key length, key bytes, report count, then per report: length, bytes",
        "// (zero padding removed). The table ends with flags 0.",
        "const uint8_t TRACE_TABLE[] PROGMEM = {",
    ]
    total = 0
    for flag, key, reports in entries():
        row = [f"TRACE_{flag}", len(key), *key, len(reports)]
        for r in reports:
            row += [len(r), *r]
        total += len(row)
        lines.append("  " + ", ".join(x if isinstance(x, str) else f"0x{x:02X}" for x in row) + ",")
    lines += ["  0", "};", f"// {total + 1} bytes", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render())
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
