"""Writes trace_data.h for the serial emulator from the mock tests' recorded traces.

    python3 hardware/serial-emulator/make_trace.py

The emulator replays the same replies FakeOximeter does (tests/hwsim.py): the PO-400's Auto-mode
exchange (tests/fixtures/cli-exchange.trace.json) and its Manual-mode download
(tests/fixtures/manual-download.trace.json). Each entry is a command key (opcode plus the
argument bytes that identify it, as hwsim.command_key) and the reports the device sent back,
stored without their zero padding. Commands that got no reply are left out: the emulator stays
silent for anything not in the table, as the strict mock does. The 0x81 model reply is not
stored; the sketch builds it from the selected model string.

The protocol-B models (PO-250, CMS50F; T-105) replay the 2014 CMS50F 3.7 capture
(tests/fixtures/cms50f37-download.trace.json): `B_REPLIES` holds the replies to `A3`, `A4`,
`A5` and `AD` as captured, `B_SAMPLES` the `A6` data as runs of (SpO2, pulse, count), which
fits the Uno's flash (8,202 samples in about 4 KB).
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, os.path.join(ROOT, "tests"))
from hwsim import Trace  # noqa: E402

FIXTURES = os.path.join(ROOT, "tests", "fixtures")
SOURCES = (("cli-exchange.trace.json", "AUTO"), ("manual-download.trace.json", "MANUAL"))
PROTOCOL_B_FIXTURE = os.path.join(FIXTURES, "cms50f37-download.trace.json")
PROTOCOL_B_OPCODES = (0xA3, 0xA4, 0xA5, 0xAD)  # answered as captured; A6 comes from B_SAMPLES
OUT = os.path.join(HERE, "trace_data.h")


def entries():
    """(flag, key bytes, [trimmed reports]) per distinct command key that got a reply."""
    seen = {}
    for name, storage in SOURCES:
        for _out, key, ins in Trace.from_json(os.path.join(FIXTURES, name)).groups:
            if key is None or key[0] in ("unlock", "destructive") or key == (0x81,) or not ins:
                continue
            flag = storage if (storage == "MANUAL" or key[0] in (0x9C, 0x9D)) else "COMMON"
            reports = [bytes(r).rstrip(b"\x00") or b"\x00" for r in ins]
            if key in seen:
                if seen[key][2] != reports:
                    raise SystemExit(f"{name}: {key} was recorded with two different replies")
                continue
            seen[key] = (flag, bytes(key), reports)
    return list(seen.values())


def protocol_b():
    """({opcode: reply bytes}, [(spo2, pulse, count)]) from the protocol-B capture."""
    with open(PROTOCOL_B_FIXTURE, encoding="utf-8") as handle:
        exchanges = json.load(handle)["exchanges"]
    replies, data = {}, b""
    for exchange in exchanges:
        if len(exchange["out"]) != 1:
            continue
        opcode = bytes.fromhex(exchange["out"][0])[2]
        if opcode in PROTOCOL_B_OPCODES:
            replies[opcode] = bytes.fromhex(exchange["in"])
        elif opcode == 0xA6:
            data = bytes.fromhex(exchange["in"])
    runs = []
    for i in range(0, len(data) - 7, 8):
        frame = data[i:i + 8]
        if frame[0] != 0x0F:
            raise SystemExit(f"{PROTOCOL_B_FIXTURE}: unexpected frame {frame.hex(' ')}")
        values = [(byte & 0x7F) | (0x80 if (frame[1] >> k) & 1 else 0) for k, byte in enumerate(frame[2:])]
        for spo2, pulse in zip(values[0::2], values[1::2]):
            if runs and runs[-1][:2] == [spo2, pulse] and runs[-1][2] < 255:
                runs[-1][2] += 1
            else:
                runs.append([spo2, pulse, 1])
    return replies, runs


def render() -> str:
    lines = [
        "// Generated by make_trace.py from tests/fixtures/*.trace.json. Do not edit by hand.",
        "#pragma once",
        "",
        "// Entry: flags, key length, key bytes, report count, then per report: length, bytes",
        "// (zero padding removed). The table ends with flags 0.",
        "const uint8_t TRACE_TABLE[] PROGMEM = {",
    ]
    total = 0
    for flag, key, reports in entries():
        row = [f"TRACE_{flag}", len(key), *key, len(reports)]
        for r in reports:
            row += [len(r), *r]
        total += len(row)
        lines.append("  " + ", ".join(x if isinstance(x, str) else f"0x{x:02X}" for x in row) + ",")
    lines += ["  0", "};", f"// {total + 1} bytes", ""]
    replies, runs = protocol_b()
    lines += [
        "// Protocol B (PO-250, CMS50F): opcode, reply length, reply bytes as captured. Ends with 0.",
        "const uint8_t B_REPLIES[] PROGMEM = {",
    ]
    for opcode in PROTOCOL_B_OPCODES:
        reply = replies[opcode]
        lines.append("  " + ", ".join(f"0x{x:02X}" for x in (opcode, len(reply), *reply)) + ",")
    lines += ["  0", "};", "", "// Protocol B A6 data: runs of SpO2, pulse, count (1..255).",
              f"const uint16_t B_SAMPLE_RUNS = {len(runs)};", "const uint8_t B_SAMPLES[] PROGMEM = {"]
    flat = [value for run in runs for value in run]
    for i in range(0, len(flat), 24):
        lines.append("  " + ", ".join(f"{x}" for x in flat[i:i + 24]) + ",")
    lines += ["};", f"// {len(flat)} bytes, {sum(run[2] for run in runs)} samples", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render())
    print(f"wrote {os.path.relpath(OUT, ROOT)}")
